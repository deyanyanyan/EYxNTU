def _download(url: str, dest: Path, retries: int = 3) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    for attempt in range(1, retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "evaltrain-acquire"})
            with urllib.request.urlopen(req, timeout=120) as r, tmp.open("wb") as f:
                while block := r.read(1 << 20):
                    f.write(block)
            tmp.replace(dest)
            return
        except OSError:
            if attempt == retries:
                raise
            time.sleep(5 * attempt)


def _fetch(name: str, src: dict, raw_root: Path) -> list[dict]:
    out_dir = raw_root / name
    rev = src["revision"]
    files: list[dict] = []
    if src["kind"] == "github_archive":
        archive = out_dir / f"{rev}.zip"
        url = f"https://codeload.github.com/{src['repo']}/zip/{rev}"
        if not archive.exists():
            _download(url, archive)
        prefix = f"{src['repo'].split('/')[1]}-{rev}/"
        with zipfile.ZipFile(archive) as z:
            for info in z.infolist():
                rel = info.filename[len(prefix) :]
                if info.is_dir() or not any(rel.startswith(m) or rel == m for m in src["members"]):
                    continue
                target = (out_dir / rel).resolve()
                if out_dir.resolve() not in target.parents:
                    raise ValueError(f"unsafe path in archive: {info.filename}")
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(z.read(info))
        files.append({"path": archive.name, "url": url, "bytes": archive.stat().st_size, "sha256": sha256_file(archive)})
        return files
    for rel in src["files"]:
        if src["kind"] == "hf_dataset":
            url = f"https://huggingface.co/datasets/{src['repo']}/resolve/{rev}/{rel}"
        else:
            url = f"https://raw.githubusercontent.com/{src['repo']}/{rev}/{rel}"
        dest = out_dir / rel
        if not dest.exists():
            print(f"[acquire] {name}: {rel}")
            _download(url, dest)
        files.append({"path": rel, "url": url, "bytes": dest.stat().st_size, "sha256": sha256_file(dest)})
    return files


def acquire(root: Path, lock_path: Path, include: set[str], update_lock: bool) -> dict:
    raw_root = root / "raw"
    lock = json.loads(lock_path.read_text()) if lock_path.exists() else {}
    manifest = {"retrieved_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "sources": {}}
    problems = []
    for name, src in SOURCES.items():
        if src.get("opt_in") and name not in include:
            continue
        files = _fetch(name, src, raw_root)
        entry = {k: v for k, v in src.items() if k not in ("files", "members")} | {"files": files}
        manifest["sources"][name] = entry
        locked = {f["path"]: f["sha256"] for f in lock.get(name, {}).get("files", [])}
        for f in files:
            if locked and locked.get(f["path"]) != f["sha256"]:
                problems.append(f"{name}/{f['path']}: sha256 {f['sha256'][:12]} != lock {str(locked.get(f['path']))[:12]}")
        if update_lock or name not in lock:
            lock[name] = {"revision": src["revision"], "files": [{"path": f["path"], "sha256": f["sha256"], "bytes": f["bytes"]} for f in files]}
    if problems and not update_lock:
        raise SystemExit("checksum mismatch against lock file:\n  " + "\n  ".join(problems))
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    lock_path.write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8")
    (raw_root / "sources.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, help="EVALTRAIN_ROOT; files go to <root>/raw/<source>/")
    ap.add_argument("--lock", default="manifests/sources.lock.json")
    ap.add_argument("--include", nargs="*", default=[], help="opt-in sources, e.g. leceval")
    ap.add_argument("--update-lock", action="store_true")
    args = ap.parse_args(argv)
    m = acquire(Path(args.root), Path(args.lock), set(args.include), args.update_lock)
    for name, s in m["sources"].items():
        print(f"{name:18s} {s['revision'][:12]}  " + ", ".join(f"{f['path']} ({f['bytes'] / 1e6:.1f} MB)" for f in s["files"]))


if __name__ == "__main__":
    main()
